import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
import db from './config/db.js';
import authRoutes from './routes/auth.js';
import bookRoutes from './routes/books.js';
import userRoutes from './routes/users.js';
import transactionRoutes from './routes/transactions.js';
dotenv.config();
const app=express();
app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173'}));
app.use(express.json());
app.get('/api/health',async(_req,res)=>{try{await db.query('SELECT 1');res.json({status:'ok',database:'connected'});}catch{res.status(500).json({status:'error',database:'disconnected'});}});
app.use('/api/auth',authRoutes);
app.use('/api/books',bookRoutes);
app.use('/api/users',userRoutes);
app.use('/api/transactions',transactionRoutes);
app.use((err,_req,res,_next)=>{console.error(err);res.status(500).json({message:'Unexpected server error.'});});
const port=process.env.PORT||5000;
app.listen(port,()=>console.log(`Library API running at http://localhost:${port}`));
